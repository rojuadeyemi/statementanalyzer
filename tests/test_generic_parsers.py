def _messy_text_pdf(path):
    """No ruled table, no readable header — only the row shapes give it away."""
    from reportlab.lib.pagesizes import A4
    from reportlab.pdfgen import canvas

    c = canvas.Canvas(str(path), pagesize=A4)
    lines = [
        "SOME MICROFINANCE BANK",
        "Statement of account for ADEOLA SAMUEL",
        "Opening Balance: 22,500.00",
        "2025 May 02 10:11 TRANSFER TO ADE 02 May 2025 -1,000.00 21,500.00 mobile 100000000000001",
        "2025 May 03 09:00 TRF FRM JOHN 03 May 2025 +5,000.00 26,500.00 mobile 100000000000002",
        "Page 1 of 1",
        "2025 May 04 12:30 AIRTIME MTN 04 May 2025 -500.00 26,000.00 mobile 100000000000003",
    ]
    y = 800
    for ln in lines:
        c.drawString(40, y, ln)
        y -= 18
    c.save()


def test_messy_text_only_pdf_is_extracted():
    pytest.importorskip("reportlab")
    import tempfile
    from pathlib import Path

    with tempfile.TemporaryDirectory() as tmp:
        pdf = Path(tmp) / "messy.pdf"
        _messy_text_pdf(pdf)
        s = load_statement(pdf)

    assert s.source == "pdf:Generic (text rows)"
    assert len(s.transactions) == 3
    assert s.transactions["direction"].tolist() == ["debit", "credit", "debit"]
    assert s.quality.reconciliation_rate == 1.0
    assert s.opening_balance == 22_500
