@pytest.mark.parametrize("text, expected", list(ROWS.values()), ids=list(ROWS))
def test_every_original_pattern_still_splits(text, expected):
    record = split_transaction_row(text)
    assert record is not None
    for key, value in expected.items():
        assert record.get(key) == value, key
    assert "--" not in record.values()


def test_dashed_balance_is_not_kept():
    record = split_transaction_row("2025 May 02 10:11 02 May 2025 TRANSFER TO ADE -1,000.00 -- mobile REF123")
    assert "balance" not in record


def test_patterns_are_precompiled_once():
    assert ROW_PATTERNS and all(hasattr(p, "match") for p in ROW_PATTERNS)


# ----------------------------------------------------- structural fallback
@pytest.mark.parametrize("text, expected", [
    ("05/07/2024 Cash deposit at branch counter 15,000.00 315,000.00",
     {"date": "05/07/2024", "narration": "Cash deposit at branch counter",
      "amount": "15,000.00", "balance": "315,000.00"}),
    ("2024-07-05 2024-07-06 SALARY PAYMENT JULY -- 450,000.00 765,000.00",
     {"value_date": "2024-07-06", "credit": "450,000.00", "balance": "765,000.00"}),
    ("12-Jan-24 USSD transfer 1,000.00 2,000.00 45,000.00 mobile ABC12345",
     {"date": "12-Jan-24", "channel": "mobile", "reference": "ABC12345"}),
])
def test_structural_fallback_handles_unknown_shapes(text, expected):
    record = split_by_structure(" ".join(text.split()))
    assert record is not None
    for key, value in expected.items():
        assert record.get(key) == value, key


def test_structural_fallback_rejects_junk():
    assert split_by_structure("Page 2 of 5") is None
    assert split_by_structure("Generated by the bank on request") is None
    assert split_transaction_row("") is None


# ------------------------------------------------------- table row helpers
def test_remove_blank_first2rows():
    assert remove_blank_first2rows(["", "", "Date", "Details", "", None]) == ["Date", "Details"]
    assert remove_blank_first2rows(["", "Date", "Amount"]) == ["Date", "Amount"]
    assert remove_blank_first2rows([]) == []


def test_known_header_is_found_and_rows_follow():
    header = KNOWN_HEADERS[0]
    table = [["ACCOUNT STATEMENT"], header,
             ["02 May 2025", "POS SHOPRITE", "REF1", "02 May 2025", "2,500.00", "", "22,500.00"]]
    found, rows = find_transaction_table([table])
    assert found == header
    assert len(rows) == 2                       # header + one transaction


def test_summary_block_is_not_mistaken_for_a_header():
    table = [["Print. Date", "Balance"], ["01/01/2024", "10,000.00"]]
    found, _ = find_transaction_table([table])
    assert found is None


def test_account_statement_title_then_real_header():
    table = [["Account Statement", "for May"],
             ["TXN DATE", "VAL DATE", "REMARKS", "DEBIT", "CREDIT", "BALANCE"],
             ["02/05/2025", "02/05/2025", "POS", "2,500.00", "", "22,500.00"]]
    found, rows = find_transaction_table([table])
    assert found[0] == "TXN DATE" and len(rows) == 2


def test_merged_single_cell_rows_are_split():
    header = ["Date", "Transaction Details", "Reference", "Value Date", "Withdrawals", "Lodgements", "Balance"]
    table = [
        [None, "02 May 2025 10:11 POS PURCHASE SHOPRITE 02 May 2025 2,500.00 -- 22,500.00 POS REF999", None],
        ["02 May 2025", "Transfer in", "REF2", "02 May 2025", "", "5,000.00", "27,500.00"],
    ]
    records = align_and_split_table(table, header)
    assert len(records) == 2
    assert records[0]["narration"] == "POS PURCHASE SHOPRITE"
    assert records[0]["debit"] == "2,500.00"
    assert records[1]["credit"] == "5,000.00" and records[1]["balance"] == "27,500.00"


def test_keystone_style_single_cell_header():
    header = ["Trans Date Value Date Narration Amount Balance\nDate extra"]
    table = [["02 May 2025", "02 May 2025", "POS SHOPRITE", "2,500.00", "22,500.00"]]
    records = align_and_split_table(table, header)
    assert records and records[0]["narration"] == "POS SHOPRITE"


def test_row_with_unmapped_header_falls_back_to_the_splitter():
    # Header the synonym list doesn't know: mapping yields nothing, so the row
    # text is re-tried through the splitters instead of being dropped.
    header = ["Col1", "Col2", "Col3"]
    table = [["05/07/2024", "Cash deposit at counter", "15,000.00 315,000.00"]]
    records = align_and_split_table(table, header)
    assert records and records[0]["balance"] == "315,000.00"


